<?php

namespace App\Controllers;

use App\Libraries\UploadGuard;
use CodeIgniter\HTTP\ResponseInterface;
use CodeIgniter\RESTful\ResourceController;
use Config\Upload;
use Throwable;

class Uploads extends ResourceController
{
    protected $format = 'json';

    public function image()
    {
        return $this->handleUpload('image', 'uploadImage');
    }

    public function document()
    {
        return $this->handleUpload('document', 'uploadDocument');
    }

    /**
     * Serve a stored reference file (e.g. quote attachments) from writable/uploads.
     * The filename is a random name generated by UploadedFile::getRandomName(), so
     * exposing it publicly is low risk. Path traversal is blocked via basename().
     */
    public function serve($filename = null): ResponseInterface
    {
        $name = basename((string) $filename);
        if ($name === '' || $name !== (string) $filename || $name === '.' || $name === '..') {
            return $this->response->setStatusCode(404)->setBody('Not Found');
        }

        $candidates = [
            WRITEPATH . 'uploads' . DIRECTORY_SEPARATOR . $name,
            WRITEPATH . 'uploads' . DIRECTORY_SEPARATOR . 'images' . DIRECTORY_SEPARATOR . $name,
            WRITEPATH . 'uploads' . DIRECTORY_SEPARATOR . 'documents' . DIRECTORY_SEPARATOR . $name,
        ];
        $path = null;
        foreach ($candidates as $candidate) {
            if (is_file($candidate)) {
                $path = $candidate;
                break;
            }
        }
        if ($path === null) {
            return $this->response->setStatusCode(404)->setBody('Not Found');
        }

        $extension = strtolower(pathinfo($name, PATHINFO_EXTENSION));
        $mimes = [
            'jpg' => 'image/jpeg',
            'jpeg' => 'image/jpeg',
            'png' => 'image/png',
            'webp' => 'image/webp',
            'pdf' => 'application/pdf',
            'csv' => 'text/csv',
        ];
        $mime = $mimes[$extension] ?? 'application/octet-stream';

        return $this->response
            ->setHeader('Content-Type', $mime)
            ->setHeader('Cache-Control', 'public, max-age=604800, immutable')
            ->setHeader('X-Content-Type-Options', 'nosniff')
            ->setBody((string) file_get_contents($path));
    }

    private function handleUpload(string $type, string $validationGroup)
    {
        try {
            // DIAG temporaire AVANT validation — où disparaît file ?
            $diagFiles = $this->request->getFiles();
            $diagFile = $this->request->getFile('file');
            $diagRawKeys = array_keys($_FILES ?? []);
            $diagGetFilesKeys = $diagFiles ? array_keys($diagFiles) : [];
            $diagGetFile = $diagFile ? [
                'clientName' => $diagFile->getClientName(),
                'size' => $diagFile->getSize(),
                'mime' => $diagFile->getClientMimeType(),
                'error' => $diagFile->getError(),
                'isValid' => $diagFile->isValid(),
                'tempName' => $diagFile->getTempName(),
            ] : null;
            $diagIni = [
                'file_uploads' => ini_get('file_uploads'),
                'upload_max_filesize' => ini_get('upload_max_filesize'),
                'post_max_size' => ini_get('post_max_size'),
                'max_file_uploads' => ini_get('max_file_uploads'),
                'upload_tmp_dir' => ini_get('upload_tmp_dir') ?: sys_get_temp_dir(),
                'tmp_dir_writable' => is_writable(ini_get('upload_tmp_dir') ?: sys_get_temp_dir()) ? 'yes' : 'no',
                'writable_uploads_writable' => is_writable(WRITEPATH . 'uploads') ? 'yes' : 'no',
                'writable_uploads_images_writable' => is_writable(WRITEPATH . 'uploads/images') ? 'yes' : 'no',
            ];
            log_message('error', 'Upload DIAG before validate: rawKeys='.json_encode($diagRawKeys).' getFilesKeys='.json_encode($diagGetFilesKeys).' getFile='.json_encode($diagGetFile).' ini='.json_encode($diagIni).' contentType='.$this->request->getHeaderLine('Content-Type'));

            if (! $this->validate($validationGroup)) {
                return $this->fail($this->validator->getErrors(), 422);
            }

            $file = $this->request->getFile('file');
            if ($file === null || !$file->isValid()) {
                return $this->fail(['file' => lang('Upload.errors.invalid_upload')], 400);
            }

            $guard = new UploadGuard();
            [$ok, $error, $meta] = $guard->validate($file, $type);
            if (! $ok) {
                return $this->fail(['file' => $error], 422);
            }

            $stored = $guard->store($file, $type);

            return $this->respondCreated([
                'message' => lang('Upload.success'),
                'type' => $type,
                'file' => [
                    'original_name' => $file->getClientName(),
                    'stored_name' => $stored['name'],
                    'mime' => $meta['mime'] ?? null,
                    'size' => $meta['size'] ?? null,
                ],
            ]);
        } catch (Throwable $e) {
            return $this->fail(lang('Common.errors.unexpected'), 500);
        }
    }
}
